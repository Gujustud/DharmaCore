# Regenerate lib/git_info.dart from current git. Run from repo root (c:\cribhub).
$ErrorActionPreference = 'Stop'
$repoRoot = if ($PSScriptRoot) { Split-Path -Parent $PSScriptRoot } else { Get-Location }
if (-not (Test-Path (Join-Path $repoRoot '.git'))) { $repoRoot = Get-Location }
Set-Location $repoRoot

$commitHash = (git rev-parse HEAD).Trim()
$shortHash  = (git rev-parse --short=7 HEAD).Trim()
$branch     = (git rev-parse --abbrev-ref HEAD).Trim()
$msg        = (git log -1 --format='%s').Trim()
$msgEscaped = $msg -replace '\\', '\\\\' -replace '"', '\"'
# Local build timestamp so About can show when this APK/web zip was produced.
$buildDate  = (Get-Date).ToString('yyyy-MM-dd HH:mm')

$content = @"
// Generated by scripts/update_git_info.ps1 - do not edit by hand

class GitInfo {
  static const String commitHash = '$commitHash';
  static const String shortHash = '$shortHash';
  static const String commitMessage = "$msgEscaped";
  static const String branch = '$branch';
  static const String buildDate = '$buildDate';
  static const String repositoryUrl = 'https://github.com/Gujustud/DharmaCore';

  static String get commitUrl => '`$repositoryUrl/commit/`$commitHash';
  static String get repoUrl => repositoryUrl;
}
"@

$outPath = Join-Path $repoRoot 'lib\git_info.dart'
$content | Set-Content -Path $outPath -Encoding UTF8 -NoNewline
Write-Host "Updated $outPath -> $shortHash @ $buildDate"
